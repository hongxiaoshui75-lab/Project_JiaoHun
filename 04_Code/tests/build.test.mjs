import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFile,stat,mkdir,writeFile } from 'node:fs/promises';
import { dirname,resolve } from 'node:path';
import { fileURLToPath,pathToFileURL } from 'node:url';
import { Script } from 'node:vm';

test('分发包可重复生成，单文件内联完整程序且无外部依赖',async()=>{
  const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
  const oldBuild=resolve(root,'../09_Builds/JiaoHun_Demo');
  await mkdir(oldBuild,{recursive:true});
  await writeFile(resolve(oldBuild,'stale-generated-test.txt'),'must not ship');
  execFileSync(process.execPath,[resolve(root,'tools/build.mjs')],{cwd:root,encoding:'utf8'});
  const build=resolve(root,'../09_Builds/JiaoHun_Demo');
  await assert.rejects(stat(resolve(build,'stale-generated-test.txt')),{code:'ENOENT'});
  const html=await readFile(resolve(build,'Demo.html'),'utf8');
  assert.doesNotMatch(html,/<script[^>]+src=/i);
  assert.doesNotMatch(html,/<link[^>]+rel="stylesheet"/i);
  const script=html.match(/<script type="module">\s*([\s\S]*?)<\/script>/)?.[1];
  assert.ok(script,'内联游戏程序应存在');
  assert.doesNotMatch(script,/^import\s|^export\s/m);
  assert.doesNotThrow(()=>new Script(script));
  assert.match(script,/fiber_report/);
  assert.match(script,/function decodeSave/);
  const sourceContent=await readFile(resolve(root,'../05_Content/demo-content.mjs'),'utf8');
  assert.equal(await readFile(resolve(build,'content/demo-content.mjs'),'utf8'),sourceContent);
  const {demoContent}=await import(pathToFileURL(resolve(build,'content/demo-content.mjs')).href);
  const {createGame,validateState}=await import(pathToFileURL(resolve(build,'core/engine.mjs')).href);
  assert.deepEqual(validateState(demoContent,createGame(demoContent)),[]);
  assert.match(await readFile(resolve(build,'server.mjs'),'utf8'),/contentRoot = resolve\(root, 'content'\)/);
  const zip=await readFile(resolve(build,'../JiaoHun_Demo.zip'));
  assert.equal(zip.readUInt32LE(0),0x04034b50);
  assert.equal(zip.readUInt32LE(zip.length-22),0x06054b50);
  assert.ok(zip.readUInt16LE(zip.length-12)>40,'分发包应包含运行美术资源');
  assert.match(script,/data:image\/png;base64,/,'单文件应内嵌图片');
  assert.match(script,/const assetCatalog=/);
  const bytes=(await stat(resolve(build,'Demo.html'))).size;
  assert.ok(bytes>1_000_000 && bytes<256*1024*1024,'有美术的离线包应在可用大小内');
  const {assetCatalog}=await import(pathToFileURL(resolve(build,'web/assets.mjs')).href);
  for(const asset of Object.values(assetCatalog))assert.ok((await stat(resolve(build,'web',asset.src.slice(1)))).size>0);
  for(const asset of Object.values(assetCatalog))assert.ok(html.includes(`data:image/png;base64,${(await readFile(resolve(build,'web',asset.src.slice(1)))).toString('base64')}`),'每个资源必须完整内嵌');
});
